using System;

/*
Что происходит с врагом после смерти (взрыв тела, призыв, лужа и т.п.). Выбирается в EnemyConfig.deathEffects.

Как и тело/тактики, модуль — только настройки в общем конфиге: всё состояние конкретного врага
держим в локальных переменных запущенной задачи, а не в полях модуля.

Новый эффект = наследник с [AddTypeMenu]; EnemyDeadState вызывает Begin() у каждого эффекта
и держит тело на сцене, пока не истечёт самое долгое из возвращённых времён.
*/
[Serializable]
public abstract class EnemyDeathEffect
{
    // Вызывается при входе в состояние смерти. Возвращает, сколько секунд тело должно ещё прожить.
    public abstract float Begin(EnemyController controller);
}
