// Роли состояний врага.
// Состояние регистрируется на роль в EnemyController.CreateStates(), а переходы идут по роли —
// поэтому архетип может подменить реализацию одной роли, не трогая остальные состояния.
// Retreat и Stagger зарезервированы: под них можно написать состояние и зарегистрировать его,
// ничего больше в базовом коде менять не придётся.
public enum EnemyStateId
{
    Idle = 0,
    Patrol = 1,
    Follow = 2,
    Attack = 3,
    Retreat = 4,
    Stagger = 5,
    Dead = 6
}
