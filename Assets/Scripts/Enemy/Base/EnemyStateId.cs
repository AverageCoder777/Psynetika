// Роли состояний (режимов) врага.
// Состояние регистрируется на роль в EnemyController.CreateStates(), а переходы идут по роли —
// поэтому архетип может подменить реализацию одной роли, не трогая остальные состояния.
// Как именно враг двигается в режиме, задают не состояния, а тактики и тело из EnemyConfig.
// Stagger зарезервирован: под него можно написать состояние и зарегистрировать его,
// ничего больше в базовом коде менять не придётся.
public enum EnemyStateId
{
    Rest = 0,     // игрок не замечен: тактика idle
    Engage = 1,   // бой между атаками: тактика engage
    Attack = 2,
    Return = 3,   // возвращение к точке спавна после потери игрока
    Stagger = 4,
    Dead = 5
}
