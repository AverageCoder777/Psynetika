using UnityEngine;

// Какую форму коллайдера строить по пиксельной маске слоя.
// Значения сериализуются числом — существующие номера не менять, новые добавлять в конец.
public enum ColliderShapeMode
{
    // Контур по границе пикселей: PolygonCollider2D с несколькими путями, склоны остаются наклонными.
    Outline = 0,

    // Прямоугольники, слитые через CompositeCollider2D в одну фигуру: стыки гладкие, но в сцене
    // это снова полигон. Нужен там, где требуется ровно один коллайдер — эффектор платформы, триггер.
    [InspectorName("Merged Boxes (Composite)")]
    MergedBoxes = 1,

    // Один прямоугольник по габаритам непрозрачных пикселей.
    BoundingBox = 2,

    // Отдельные BoxCollider2D без слияния: каждый прямоугольник виден в сцене и правится руками.
    Boxes = 3
}
