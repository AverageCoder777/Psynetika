// Какую форму коллайдера строить по пиксельной маске слоя.
public enum ColliderShapeMode
{
    // Контур по границе пикселей: PolygonCollider2D с несколькими путями, склоны остаются наклонными.
    Outline = 0,

    // Разбиение на прямоугольники: BoxCollider2D + CompositeCollider2D, склоны превращаются в лесенку.
    Boxes = 1,

    // Один прямоугольник по габаритам непрозрачных пикселей.
    BoundingBox = 2
}
