// Контракт результатов нод:
// Success — нода отработала, последовательность продолжается.
// Failure — условие не выполнено; текущая последовательность (корень, Sequence, ветка Branch)
//           останавливается, но это не ошибка каста: TimedTickNode, например, пропускает
//           остаток тика и ждёт следующий.
// Cancelled — каст прерван целиком (смерть, отмена извне); распространяется до раннера,
//             остальные ноды не выполняются, cleanup-действия отрабатывают в finally.
public enum NodeResult
{
    Success = 0,
    Failure = 1,
    Cancelled = 2
}
